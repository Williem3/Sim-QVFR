"""Generates src/launcher/ui/theme_tokens.h from the launcher kit's tokens.json.

Usage: python tools/gen_launcher_theme.py [tokens.json] [out.h]
Colours become 0xRRGGBB per theme (light, dark); {name} references resolve to the named token.
Type styles, spacing, radii and sizes become constants in DIPs (the kit's px at 96 DPI).
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'docs', 'qvfr-launcher-kit', 'qvfr-launcher-kit', 'tokens.json')
OUT = os.path.join(ROOT, 'src', 'launcher', 'ui', 'theme_tokens.h')


def ident(name):
    return re.sub(r'[^0-9a-zA-Z]+', '_', name).strip('_')


def px(value):
    return float(value.replace('px', ''))


def main(src=SRC, out=OUT):
    tokens = json.load(open(src, encoding='utf-8'))
    colors = {t['name']: t['value'] for t in tokens['color']['tokens']}

    def resolve(name, theme):
        v = colors[name]
        v = v[theme] if isinstance(v, dict) else v
        m = re.fullmatch(r'\{(.+)\}', v)
        return resolve(m.group(1), theme) if m else v

    lines = [
        '// Generated by tools/gen_launcher_theme.py from docs/qvfr-launcher-kit/qvfr-launcher-kit/tokens.json.',
        '// Do not edit by hand; edit the kit and regenerate.',
        '#pragma once',
        '',
        '#include <cstdint>',
        '',
        'namespace aceqv::launcher::ui::tokens {',
        '',
        '// Colours, 0xRRGGBB.',
        'struct Colors {',
    ]
    names = list(colors)
    for n in names:
        lines.append(f'    uint32_t {ident(n)};')
    lines.append('};')
    for theme in ('light', 'dark'):
        lines.append(f'inline constexpr Colors k{theme.capitalize()} = {{')
        for n in names:
            lines.append(f'    0x{resolve(n, theme).lstrip("#").lower()},  // {n}')
        lines.append('};')
    lines += ['', '// Type styles: size and line height in DIPs, weight, monospaced family.',
              'struct TypeStyle {', '    float size, lineHeight;', '    int weight;', '    bool mono;', '};']
    for group in tokens['type']['groups']:
        mono = group['family'] == 'mono'
        for st in group['styles']:
            lines.append(f'inline constexpr TypeStyle k{ident(st["name"]).title().replace("_", "")} = '
                         f'{{{px(st["fontSize"])}f, {px(st["lineHeight"])}f, {st["fontWeight"]}, {"true" if mono else "false"}}};')
    for section in ('spacing', 'radius', 'size'):
        lines += ['', f'// {section.capitalize()} (DIPs).']
        for t in tokens[section]['tokens']:
            lines.append(f'inline constexpr float k{ident(t["name"]).title().replace("_", "")} = {px(t["value"])}f;')
    lines += ['', '}  // namespace aceqv::launcher::ui::tokens', '']
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('wrote', out)


if __name__ == '__main__':
    main(*sys.argv[1:])
