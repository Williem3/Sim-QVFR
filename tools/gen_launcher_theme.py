"""Generates src/launcher/ui/theme_tokens.h (and docs/ui/tokens.css) from docs/ui/tokens.json.

Usage: python tools/gen_launcher_theme.py [tokens.json] [out.h]
Colours become 0xRRGGBB per theme (light, dark); {name} references resolve to the named token. Type styles carry their
family (Inter or Jost), weight, tabular figures, uppercase and letter spacing. Spacing, radii and sizes become
constants in DIPs (px at 96 DPI).
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'docs', 'ui', 'tokens.json')
OUT = os.path.join(ROOT, 'src', 'launcher', 'ui', 'theme_tokens.h')


def ident(name):
    return re.sub(r'[^0-9a-zA-Z]+', '_', name).strip('_')


def camel(name):
    return ''.join(part.capitalize() for part in ident(name).split('_'))


def px(value):
    return float(value.replace('px', ''))


def em(value):
    return float(value.replace('em', '')) if value else 0.0


def main(src=SRC, out=OUT):
    tokens = json.load(open(src, encoding='utf-8'))
    colors = {t['name']: t['value'] for t in tokens['color']['tokens']}

    def resolve(name, theme):
        v = colors[name]
        v = v[theme] if isinstance(v, dict) else v
        m = re.fullmatch(r'\{(.+)\}', v)
        return resolve(m.group(1), theme) if m else v

    rel = os.path.relpath(src, ROOT).replace('\\', '/')
    lines = [
        f'// Generated by tools/gen_launcher_theme.py from {rel}.',
        '// Do not edit by hand; edit the tokens and regenerate.',
        '#pragma once',
        '',
        '#include <cstdint>',
        '',
        'namespace simqvfr::launcher::ui::tokens {',
        '',
        '// Colours, 0xRRGGBB. The names after the first alias are the old kit\'s, mapped onto the new ones until every',
        '// page uses those.',
        'struct Colors {',
    ]
    names = list(colors)
    for n in names:
        lines.append(f'    uint32_t {ident(n)};')
    lines.append('};')
    for theme in ('light', 'dark'):
        lines.append(f'inline constexpr Colors k{theme.capitalize()} = {{')
        for n in names:
            lines.append(f'    0x{resolve(n, theme).lstrip("#").lower()},  // {n}')
        lines.append('};')
    # Each game's marker colour (tokens.json "games").
    palettes = tokens.get('games', {}).get('palettes', [])
    accent_keys = ('accent', 'accent-fill', 'on-accent', 'focus-ring')
    lines += ['', '// Each game\'s marker colours (tokens.json "games"): its rail marker and, in the old layout, its tab.',
              'struct Accent {', *[f'    uint32_t {ident(k)};' for k in accent_keys], '};',
              'struct GamePalette {', '    const char* id;  // games::GameInfo::id', '    Accent light, dark;', '};',
              'inline constexpr GamePalette kGamePalettes[] = {']
    for p in palettes:
        def accent(theme):
            return '{' + ', '.join(f'0x{p[k][theme].lstrip("#").lower()}' for k in accent_keys) + '}'
        lines.append(f'    {{"{p["id"]}", {accent("light")}, {accent("dark")}}},  // {p["name"]}')
    lines.append('};')
    # Type.
    families = tokens['type']['families']
    family_ids = list(families)
    lines += ['', '// Type: the bundled families (src/launcher/launcher.rc), and the styles.',
              'enum class Family : uint8_t { ' + ', '.join(camel(f) for f in family_ids) + ' };',
              'struct FamilyInfo {', '    const wchar_t* name;      // the family name in the font files',
              '    const wchar_t* fallback;  // installed families to use when the bundled one can\'t be loaded', '};',
              'inline constexpr FamilyInfo kFamilies[] = {']
    for f in family_ids:
        lines.append(f'    {{L"{families[f]["name"]}", L"{families[f]["fallback"]}"}},  // {camel(f)}')
    lines += ['};',
              '// Size and line height in DIPs; weight; tabular figures; family; uppercase; letter spacing in em.',
              'struct TypeStyle {', '    float size, lineHeight;', '    int weight;', '    bool tabular = false;',
              f'    Family family = Family::{camel(family_ids[0])};', '    bool upper = false;', '    float tracking = 0;', '};']
    for st in tokens['type']['styles']:
        fields = [f'{px(st["fontSize"])}f', f'{px(st["lineHeight"])}f', str(st['fontWeight']),
                  'true' if st.get('tabular') else 'false', f'Family::{camel(st["family"])}',
                  'true' if st.get('uppercase') else 'false', f'{em(st.get("letterSpacing", ""))}f']
        lines.append(f'inline constexpr TypeStyle k{camel(st["name"])} = {{{", ".join(fields)}}};')
    for section in ('spacing', 'radius', 'size'):
        lines += ['', f'// {section.capitalize()} (DIPs).']
        for t in tokens[section]['tokens']:
            lines.append(f'inline constexpr float k{camel(t["name"])} = {px(t["value"])}f;')
    lines += ['', '}  // namespace simqvfr::launcher::ui::tokens', '']
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))
    print('wrote', out)
    write_css(tokens, resolve, os.path.join(os.path.dirname(src), 'tokens.css'))


def write_css(tokens, resolve, out):
    """tokens.css: the same values as CSS variables, for mockups and previews."""
    names = [t['name'] for t in tokens['color']['tokens']]

    def theme_vars(theme, indent='  '):
        rows = []
        for n in names:
            raw = next(t['value'] for t in tokens['color']['tokens'] if t['name'] == n)
            raw = raw[theme] if isinstance(raw, dict) else raw
            m = re.fullmatch(r'\{(.+)\}', raw)
            rows.append(f'{indent}--{n}: {"var(--" + m.group(1) + ")" if m else resolve(n, theme)};')
        rows.append(f'{indent}color-scheme: {theme};')
        return rows

    css = ['/* Sim-QVFR Launcher: generated from tokens.json by tools/gen_launcher_theme.py */',
           ':root, [data-theme="light"] {', *theme_vars('light'), '}',
           '@media (prefers-color-scheme: dark) { :root:not([data-theme="light"]) {', *theme_vars('dark'), '} }',
           '[data-theme="dark"] {', *theme_vars('dark'), '}', ':root {']
    for section in ('spacing', 'radius', 'size'):
        css += [f'  --{t["name"]}: {t["value"]};' for t in tokens[section]['tokens']]
    for fid, fam in tokens['type']['families'].items():
        css.append(f'  --font-{fid}: "{fam["name"]}", {fam["fallback"]}, sans-serif;')
    css.append('}')
    for st in tokens['type']['styles']:
        rules = [f'font-family: var(--font-{st["family"]})', f'font-size: {st["fontSize"]}',
                 f'line-height: {st["lineHeight"]}', f'font-weight: {st["fontWeight"]}']
        if st.get('uppercase'):
            rules.append('text-transform: uppercase')
        if st.get('letterSpacing'):
            rules.append(f'letter-spacing: {st["letterSpacing"]}')
        if st.get('tabular'):
            rules.append('font-variant-numeric: tabular-nums')
        css.append(f'.type-{st["name"]} {{ {"; ".join(rules)}; }}')
    open(out, 'w', encoding='utf-8', newline='\n').write('\n'.join(css) + '\n')
    print('wrote', out)


if __name__ == '__main__':
    main(*sys.argv[1:])
