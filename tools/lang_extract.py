"""Collects the launcher's and the headset menu's English text into lang/_template.ini, and keeps lang/<code>.ini in step.

Usage:
  python tools/lang_extract.py            writes lang/_template.ini from every tr / trf / I18N in src/
  python tools/lang_extract.py --sync     also rewrites each lang/<code>.ini in the template's order: new English
                                          lines get an empty translation, lines the app no longer has move to the end
  python tools/lang_extract.py --check    changes nothing; exit 1 when the template is out of date or a translation's
                                          {placeholders} differ from its English (each language's coverage printed)

The text is what the C++ code passes as wide string literals (adjacent literals joined, escapes resolved) to tr( ),
trf( ) or I18N( ) (src/lang.h). The file format is src/lang.h's: [language] code/name, then [strings] pairs of
`en = <English>` and `<code> = <translation>`; a value is bare (trimmed) or in double quotes (spaces kept), with
\\n \\t \\\\ \\" escapes.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
LANG = os.path.join(ROOT, 'lang')
TEMPLATE = os.path.join(LANG, '_template.ini')
MARKERS = {'tr', 'trf', 'I18N'}

HEADER_TEMPLATE = """\
; Sim-QVFR's text, for translating the launcher and the headset menu. Generated by tools/lang_extract.py: don't edit
; this file, copy it.
;
; To translate: copy this file to <code>.ini in the same folder (de.ini, pl.ini, fr.ini, es.ini, pt-BR.ini), set
; [language] below, and write each translation on the "xx =" line under its English (xx may stay or become your code).
"""

HEADER_LANGUAGE = """\
; Sim-QVFR in {name}. Each translation goes on the line under its English. tools/lang_extract.py --sync keeps the
; lines in step with the app (new English lines added empty, translations kept).
"""

RULES = """\
;
; A line left empty shows in English. Keep every {placeholder} as it is (its place in the sentence may move): a
; translation whose placeholders differ from the English's is ignored. A value with spaces at its start or end goes in
; "double quotes". Write a backslash as \\\\, a line break as \\n. Save as UTF-8.
"""

# ---- A small C++ lexer: identifiers, string literals (joined later), punctuation; comments and chars skipped. -----

ESCAPES = {'n': '\n', 't': '\t', 'r': '\r', '0': '\0', '\\': '\\', '"': '"', "'": "'", 'a': '\a', 'b': '\b',
           'f': '\f', 'v': '\v', '?': '?'}


def unescape_cpp(body, where):
    out, i = [], 0
    while i < len(body):
        c = body[i]
        if c != '\\':
            out.append(c)
            i += 1
            continue
        e = body[i + 1]
        if e == 'x':
            m = re.match(r'[0-9a-fA-F]+', body[i + 2:])
            out.append(chr(int(m.group(0), 16)))
            i += 2 + len(m.group(0))
        elif e == 'u':
            out.append(chr(int(body[i + 2:i + 6], 16)))
            i += 6
        elif e == 'U':
            out.append(chr(int(body[i + 2:i + 10], 16)))
            i += 10
        elif e in ESCAPES:
            out.append(ESCAPES[e])
            i += 2
        else:
            raise SystemExit(f'{where}: unknown escape \\{e}')
    return ''.join(out)


def tokens(text, path):
    i, line, n = 0, 1, len(text)
    line_start = True  # only blanks since the last newline: a # there starts a preprocessor line
    while i < n:
        c = text[i]
        if c == '\n':
            line += 1
            i += 1
            line_start = True
            continue
        if c.isspace():
            i += 1
            continue
        starts_line, line_start = line_start, False
        if text.startswith('//', i):
            j = text.find('\n', i)
            i = n if j < 0 else j
        elif text.startswith('/*', i):
            j = text.find('*/', i + 2)
            j = n if j < 0 else j + 2
            line += text.count('\n', i, j)
            i = j
        elif c == '#' and starts_line:
            # A preprocessor line (with its continuations) says nothing to translate.
            while i < n and text[i] != '\n':
                if text[i] == '\\' and i + 1 < n and text[i + 1] == '\n':
                    line += 1
                    i += 1
                i += 1
        elif c.isdigit():  # a number, digit separators (1'000) and all
            i += len(re.match(r"[0-9][0-9A-Za-z_.']*", text[i:]).group(0))
        elif c.isalpha() or c == '_':
            m = re.match(r'[A-Za-z_0-9]+', text[i:])
            word = m.group(0)
            j = i + len(word)
            if j < n and text[j] in '"\'' and word in ('L', 'u8', 'u', 'U', 'R', 'LR', 'u8R', 'uR', 'UR'):
                raw = word.endswith('R')
                if raw:  # R"delim(...)delim"
                    k = text.index('(', j)
                    delim = text[j + 1:k]
                    end = text.index(')' + delim + '"', k)
                    body = text[k + 1:end]
                    line_start = line
                    line += body.count('\n')
                    i = end + len(delim) + 2
                    yield ('str', body, word.startswith('L'), line_start)
                    continue
                if text[j] == "'":
                    i = skip_quoted(text, j, "'")
                    continue
                end = skip_quoted(text, j, '"')
                yield ('str', unescape_cpp(text[j + 1:end - 1], f'{path}:{line}'), word == 'L', line)
                i = end
                continue
            yield ('id', word, None, line)
            i = j
        elif c == '"':
            end = skip_quoted(text, i, '"')
            yield ('str', unescape_cpp(text[i + 1:end - 1], f'{path}:{line}'), False, line)
            i = end
        elif c == "'":
            i = skip_quoted(text, i, "'")
        elif text.startswith('->', i) or text.startswith('::', i):
            yield ('punct', text[i:i + 2], None, line)
            i += 2
        else:
            yield ('punct', c, None, line)
            i += 1


def skip_quoted(text, i, quote):
    j = i + 1
    while text[j] != quote:
        j += 2 if text[j] == '\\' else 1
    return j + 1


def messages(path):
    """(english, line) for each marked literal in `path`, in order."""
    with open(path, encoding='utf-8-sig') as f:
        toks = list(tokens(f.read(), path))
    found = []
    for k, (kind, value, _, line) in enumerate(toks):
        if kind != 'id' or value not in MARKERS:
            continue
        if k > 0 and toks[k - 1][0] == 'punct' and toks[k - 1][1] in ('.', '->'):
            continue  # someone's member named tr
        if k + 2 >= len(toks) or toks[k + 1][1] != '(' or toks[k + 2][0] != 'str':
            continue  # tr(variable): nothing to collect
        parts, j = [], k + 2
        while j < len(toks) and toks[j][0] == 'str':
            if not toks[j][2]:
                raise SystemExit(f'{path}:{toks[j][3]}: {value}( takes wide literals (L"...")')
            parts.append(toks[j][1])
            j += 1
        if toks[j][1] not in (')', ','):
            continue  # tr(L"a" + x): a sum, not a literal
        found.append((''.join(parts), line))
    return found


def collect():
    """[(english, 'src/...:line'), ...]: every marked text once, files in path order."""
    seen, out = set(), []
    for base, dirs, files in os.walk(SRC):
        dirs.sort()
        for name in sorted(files):
            if not name.endswith(('.cpp', '.h')):
                continue
            path = os.path.join(base, name)
            rel = os.path.relpath(path, ROOT).replace('\\', '/')
            for english, line in messages(path):
                if english not in seen:
                    seen.add(english)
                    out.append((english, f'{rel}:{line}'))
    return out


# ---- The language files (src/lang.h's format). --------------------------------------------------------------------

def quote(value):
    """`value` as a file value: escaped, in quotes when its ends are spaces or it starts with a quote."""
    v = value.replace('\\', '\\\\').replace('\n', '\\n').replace('\t', '\\t')
    if v != v.strip(' ') or v.startswith('"'):
        return '"' + v.replace('"', '\\"') + '"'
    return v


def unquote(raw):
    raw = raw.strip(' \t\r')
    quoted = len(raw) >= 2 and raw[0] == '"' and raw[-1] == '"'
    if quoted:
        raw = raw[1:-1]
    out, i = [], 0
    while i < len(raw):
        if raw[i] == '\\' and i + 1 < len(raw):
            out.append({'n': '\n', 't': '\t', '\\': '\\', '"': '"'}.get(raw[i + 1], '\\' + raw[i + 1]))
            i += 2
        else:
            out.append(raw[i])
            i += 1
    return ''.join(out)


def read_lang(path):
    """(code, name, {english: translation}) of a language file; empty translations kept as ''."""
    code, name, pairs = '', '', {}
    section, english = None, None
    with open(path, encoding='utf-8-sig') as f:
        for line in f:
            s = line.strip()
            if not s or s[0] in ';#':
                continue
            if s.startswith('['):
                section, english = s.strip('[]').strip().lower(), None
                continue
            if '=' not in s:
                continue
            key, value = s.split('=', 1)
            key, value = key.strip(), unquote(value)
            if section == 'language':
                if key.lower() == 'code':
                    code = value
                elif key.lower() == 'name':
                    name = value
            elif section == 'strings':
                if key.lower() == 'en':
                    english = value
                elif english is not None:
                    pairs[english] = value
                    english = None
    return code, name, pairs


def write_lang(path, code, name, entries, pairs, stale=()):
    lines = ((HEADER_LANGUAGE.format(name=name or code) if code else HEADER_TEMPLATE) + RULES).splitlines()
    lines += ['', '[language]', f'code = {code}', f'name = {name}', '', '[strings]']
    last_file = None
    for english, where in entries:
        file = where.rsplit(':', 1)[0]
        if file != last_file:
            lines += ['', f'; {file}']
            last_file = file
        lines += [f'en = {quote(english)}', f'{code or "xx"} = {quote(pairs.get(english, ""))}']
    if stale:
        lines += ['', '; No longer in Sim-QVFR (kept to reuse; ignored where the English isn\'t shown any more):']
        for english in stale:
            lines += [f'en = {quote(english)}', f'{code} = {quote(pairs[english])}']
    text = '\r\n'.join(lines) + '\r\n'
    old = open(path, encoding='utf-8-sig', newline='').read() if os.path.exists(path) else None
    return text, old


def placeholders(s):
    s = s.replace('{{', '').replace('}}', '')
    return sorted(re.findall(r'\{([A-Za-z0-9_]{1,32})\}', s))


def main(argv):
    mode = argv[1] if len(argv) > 1 else ''
    if mode not in ('', '--sync', '--check'):
        raise SystemExit(__doc__)
    entries = collect()
    os.makedirs(LANG, exist_ok=True)
    bad = False
    text, old = write_lang(TEMPLATE, '', '', entries, {})
    if text != old:
        if mode == '--check':
            print('lang/_template.ini is out of date: run python tools/lang_extract.py --sync')
            bad = True
        else:
            open(TEMPLATE, 'w', encoding='utf-8', newline='').write(text)
            print(f'lang/_template.ini: {len(entries)} lines')
    english = {e for e, _ in entries}
    for name in sorted(os.listdir(LANG)):
        if not name.endswith('.ini') or name.startswith('_'):
            continue
        path = os.path.join(LANG, name)
        code, own, pairs = read_lang(path)
        code = code or name[:-4]
        done = sum(1 for e in english if pairs.get(e))
        stale = [e for e in pairs if e not in english and pairs[e]]
        wrong = [e for e, t in pairs.items() if t and placeholders(e) != placeholders(t)]
        print(f'lang/{name}: {done}/{len(english)} translated, {len(stale)} no longer used, {len(wrong)} with wrong placeholders')
        for e in wrong:
            print(f'  placeholders differ: {e[:70]!r}')
        bad |= bool(wrong) and mode == '--check'
        if mode in ('--sync', '--check'):
            new, current = write_lang(path, code, own, entries, pairs, stale)
            if new != current:
                if mode == '--check':
                    print(f'  lang/{name} is out of step with the template: run --sync')
                    bad = True
                else:
                    open(path, 'w', encoding='utf-8', newline='').write(new)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
